/**
 * 이미 밴디에 등록된 동아리.
 *
 * 가입할 때 「우리 동아리」 를 여기서 찾습니다. 찾으면 부원으로 들어가고,
 * 없으면 새로 만듭니다. 학교로 먼저 좁히는 이유는 같은 이름이 학교마다
 * 있기 때문입니다 — 「소리」 라는 동아리는 어느 학교에나 하나씩 있습니다.
 *
 * MOCK: 실제로는 서버가 학교로 질의합니다.
 */
export interface KnownClub {
  id: string
  name: string
  /**
   * 학교. 연합 동아리 · 직장인 밴드 · 지역 밴드는 학교가 없습니다.
   * 처음에 필수로 두었는데, 그러면 그런 동아리는 들어올 자리가 없습니다.
   */
  school: string | null
  /** 학교가 없을 때 대신 보여 줄 것 — 「서울 연합」 「노원 직장인」 */
  area?: string
  /**
   * 참여 코드 — 운영진이 단톡에 올리는 값.
   *
   * 앱은 다섯 군데에서 「운영진에게 받은 참여 코드로 들어온다」 고 말하는데
   * 그 코드를 넣을 자리가 없었습니다. 이름으로만 찾을 수 있었습니다.
   * 이제 이름 칸에 코드를 적어도 찾습니다.
   */
  code: string
  /** 부원 수 — 맞는 동아리인지 사람이 알아보는 단서 */
  members: number
  since: string
}

